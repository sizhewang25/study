r"""The slug inventory: every number of the paper, where it comes from, and whether it still holds.

    python -m scripts.analysis.v5.paper_values.inventory

Joins the template's `slugs.orig.json` (each use: file, line, the literal the
paper printed) with the registry (source, getter) and the values files
(the value generated now), and writes `paper/template/SLUGS.md`:

1. mismatches -- the paper's literal differs from the generated value (a
   stale number in the paper, a runtime timed on another machine, or a wrong
   mapping);
2. failing claims -- worded statements the data no longer supports;
3. every slug, by section, with its source.
"""

from __future__ import annotations

import json
from pathlib import Path

import typer

from scripts.analysis.v5.paper_values import registry as R
from scripts.analysis.v5.paper_values.render import PAPER_OUT, evaluate_derived, merge_values
from scripts.analysis.v5.paper_values.slugify import DEFAULT_TEMPLATE


def _norm(s: str) -> str:
    return s.replace(" ", "").replace("~", "")


def rows(template: Path, values: list[Path]) -> tuple[list[dict], dict]:
    R.load_all()
    slugs, claims, _ = merge_values(values) if values else ({}, {}, [])
    evaluate_derived(slugs, claims)
    uses = json.loads((template / "slugs.orig.json").read_text())["uses"]
    out = []
    for u in uses:
        key = u["key"]
        reg = R.SLUGS.get(key) or R.DERIVED.get(key)
        rec = slugs.get(key, {})
        fmt = u["fmt"] or (reg.fmt if reg else None)
        now = None
        if rec.get("status") == "ok":
            now = R.render_value(rec["value"], fmt)
        out.append({
            **u, "registered": reg is not None,
            "group": getattr(reg, "group", "derived") if reg else "?",
            "section": reg.section if reg else "",
            "source": reg.source if reg else "UNREGISTERED",
            "now": now, "status": rec.get("status", "not generated"),
            "match": None if now is None else _norm(now) == _norm(u["literal"]),
        })
    return out, claims


def markdown(rs: list[dict], claims: dict) -> str:
    def cell(s):
        return str(s).replace("|", "\\|").replace("\n", " ")

    keys = {r["key"] for r in rs}
    mism = [r for r in rs if r["match"] is False]
    ungen = [r for r in rs if r["match"] is None]
    failing = {k: v for k, v in claims.items() if v.get("holds") is False}
    unknown = {k: v for k, v in claims.items() if v.get("holds") is None}
    unused = sorted(k for k in R.SLUGS if k not in keys)
    lines = [
        "# Paper numbers: slug inventory",
        "",
        "Generated by `python -m scripts.analysis.v5.paper_values.inventory`; do not edit.",
        "",
        f"{len(rs)} uses of {len(keys)} slugs; {len(mism)} uses differ from the generated value, "
        f"{len(ungen)} have no generated value here; {len(failing)} of {len(claims)} claims fail, "
        f"{len(unknown)} unevaluated.",
        "",
        "## 1. Paper literal differs from the generated value",
        "",
        "| Key | Paper | Now | Where | Source |",
        "|---|---|---|---|---|",
        *[f"| `{r['key']}` | {cell(r['literal'])} | {cell(r['now'])} | {r['file']}:{r['line']} | {cell(r['source'])} |"
          for r in mism],
        "",
        "## 2. Claims that fail",
        "",
        "| Claim | Text | Detail |",
        "|---|---|---|",
        *[f"| `{k}` | {cell(v['text'])} | {cell(v['detail'])} |" for k, v in failing.items()],
        "",
        "## 3. Not generated on this machine",
        "",
        "| Key | Paper | Group | Status |",
        "|---|---|---|---|",
        *[f"| `{r['key']}` | {cell(r['literal'])} | {r['group']} | {r['status']} |" for r in ungen],
        *([""] + ["Claims not evaluated: " + ", ".join(f"`{k}`" for k in unknown)] if unknown else []),
        "",
        "## 4. Every slug",
        "",
        "| Key | Section | Group | Paper | Now | Where | Source |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rs, key=lambda r: (r["file"], r["line"])):
        lines.append(f"| `{r['key']}` | {r['section']} | {r['group']} | {cell(r['literal'])} | {cell(r['now'])} "
                     f"| {r['file']}:{r['line']} | {cell(r['source'])} |")
    lines += ["", "## 5. Registered but not in the template", "",
              "Read only by claims or derived slugs, or not printed:", "",
              ", ".join(f"`{k}`" for k in unused) or "(none)", "",
              "## 6. Every claim", "", "| Claim | Holds | Text | Detail |", "|---|---|---|---|",
              *[f"| `{k}` | {v.get('holds')} | {cell(v['text'])} | {cell(v.get('detail'))} |"
                for k, v in sorted(claims.items())], ""]
    return "\n".join(lines)


app = typer.Typer(add_completion=False)


@app.command()
def main(
    values: list[Path] = typer.Option(None, "--values", help="Default: every file in outputs/paper/values."),
    template: Path = typer.Option(DEFAULT_TEMPLATE),
    out: Path = typer.Option(None, help="Default: <template>/SLUGS.md."),
) -> None:
    values = values or sorted((PAPER_OUT / "values").glob("*.json"))
    rs, claims = rows(template, values)
    unreg = sorted({r["key"] for r in rs if not r["registered"]})
    out = out or template / "SLUGS.md"
    out.write_text(markdown(rs, claims))
    n_mis = sum(r["match"] is False for r in rs)
    typer.echo(f"wrote {out}: {len(rs)} uses, {n_mis} mismatches, "
               f"{sum(v.get('holds') is False for v in claims.values())} failing claims")
    if unreg:
        typer.echo(f"error: template uses unregistered slugs: {', '.join(unreg)}", err=True)
        raise typer.Exit(1)


if __name__ == "__main__":
    app()
